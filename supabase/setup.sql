-- =====================================================================
-- OnlineCourseCompare: database setup for course reviews
-- ("Worth it or money grab?", the AI slop meter, tags and comments)
--
-- Run this in your Supabase project:
--   Supabase dashboard -> your project -> SQL Editor -> New query
--   -> paste this whole file -> Run
--
-- Safe to run again: it only adds what is missing and refreshes the tag
-- list, views and functions. It never deletes reviews. Back up the
-- reviews themselves separately (see the setup guide PDF).
--
-- The course list is NOT in the database. It lives in the website
-- (src/data/courses.json), so the site keeps working even if this
-- database is paused or gone. Only reviews depend on it.
--
-- Nobody signs in. voter_hash is a one-way hash the website's server
-- makes from the visitor's connection: one review per visitor per course
-- (which they can edit), and no IP address is ever stored.
-- =====================================================================


-- Version 1 of this script made a simpler course_votes table. Remove it
-- if it is still empty; if anyone has voted in it, leave it alone.
do $$
begin
  if to_regclass('public.course_votes') is not null then
    if not exists (select 1 from public.course_votes) then
      drop view if exists public.course_vote_totals;
      drop view if exists public.platform_vote_totals;
      drop table public.course_votes;
    end if;
  end if;
end $$;


-- ---------------------------------------------------------------------
-- Reviews
-- ---------------------------------------------------------------------
create table if not exists public.course_reviews (
  id          bigint generated by default as identity primary key,
  course_id   bigint      not null,   -- "id" from src/data/courses.json
  platform    text        not null,   -- 'Udemy', 'Coursera', ...
  voter_hash  text        not null,

  -- "Did you take this course?" Only people who did can review it.
  took_course text        not null
    check (took_course in ('finished', 'in_progress', 'dropped')),

  -- The one-tap answer every review has.
  verdict     text        not null check (verdict in ('worth_it', 'money_grab')),

  -- Optional 1-5 scores.
  --   ai_slop:    1 = made by a real person, 5 = mostly AI filler
  --   learned:    1 = learned nothing,       5 = learned a lot
  --   difficulty: 1 = very easy,             5 = very hard
  ai_slop     smallint    check (ai_slop between 1 and 5),
  learned     smallint    check (learned between 1 and 5),
  difficulty  smallint    check (difficulty between 1 and 5),
  paid        text
    check (paid in ('free', 'discount', 'full_price', 'subscription')),
  comment     text        check (char_length(comment) between 10 and 2000),

  -- Hidden reviews are not shown anywhere. 3 reports hide one
  -- automatically; change it back in the Table Editor if it was fine.
  status      text        not null default 'published'
    check (status in ('published', 'hidden')),

  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint course_reviews_one_per_voter unique (course_id, voter_hash)
);

create index if not exists course_reviews_platform_idx
  on public.course_reviews (platform);
create index if not exists course_reviews_voter_recent_idx
  on public.course_reviews (voter_hash, updated_at);


