  on public.course_review_tags (tag);


-- ---------------------------------------------------------------------
-- "Was this review helpful?" and "Report this review"
-- ---------------------------------------------------------------------
create table if not exists public.review_helpful_votes (
  review_id  bigint      not null references public.course_reviews (id) on delete cascade,
  voter_hash text        not null,
  helpful    boolean     not null,
  created_at timestamptz not null default now(),
  primary key (review_id, voter_hash)
);

create table if not exists public.review_reports (
  review_id  bigint      not null references public.course_reviews (id) on delete cascade,
  voter_hash text        not null,
  reason     text        not null
    check (reason in ('spam', 'offensive', 'fake', 'off_topic', 'personal_info')),
  details    text        check (char_length(details) <= 500),
  created_at timestamptz not null default now(),
  primary key (review_id, voter_hash)
);

create or replace function public.hide_reported_review()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (select count(*) from public.review_reports where review_id = new.review_id) >= 3 then
    update public.course_reviews set status = 'hidden' where id = new.review_id;
  end if;
  return new;
end;
$$;

create or replace trigger review_reports_hide_after_3
  after insert on public.review_reports
  for each row execute function public.hide_reported_review();


-- ---------------------------------------------------------------------
-- Writing a review: one call saves the review and its tags together.
-- Sending the same voter_hash and course again edits the review.
-- ---------------------------------------------------------------------
create or replace function public.submit_review(
  p_course_id   bigint,
  p_platform    text,
  p_voter_hash  text,
  p_took_course text,
  p_verdict     text,
  p_ai_slop     integer default null,
  p_learned     integer default null,
  p_difficulty  integer default null,
  p_paid        text    default null,
  p_comment     text    default null,
  p_tags        text[]  default '{}'
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_id bigint;
begin
  if coalesce(array_length(p_tags, 1), 0) > 5 then
    raise exception 'Pick at most 5 tags';
  end if;

  -- Spam brake: one visitor can write or edit at most 20 reviews a day.
  if (select count(*) from public.course_reviews
      where voter_hash = p_voter_hash
        and course_id <> p_course_id
        and updated_at > now() - interval '1 day') >= 20 then
    raise exception 'Too many reviews today';
  end if;

  insert into public.course_reviews as r
    (course_id, platform, voter_hash, took_course, verdict,
     ai_slop, learned, difficulty, paid, comment)
  values
    (p_course_id, p_platform, p_voter_hash, p_took_course, p_verdict,
     p_ai_slop, p_learned, p_difficulty, p_paid, nullif(btrim(p_comment), ''))
  on conflict on constraint course_reviews_one_per_voter do update set
    took_course = excluded.took_course,
    verdict     = excluded.verdict,
    ai_slop     = excluded.ai_slop,
    learned     = excluded.learned,
    difficulty  = excluded.difficulty,
    paid        = excluded.paid,
    comment     = excluded.comment,
    updated_at  = now()      -- status is kept: editing never un-hides a review
  returning r.id into v_id;

  delete from public.course_review_tags where review_id = v_id;
  insert into public.course_review_tags (review_id, tag)
    select distinct v_id, t from unnest(coalesce(p_tags, '{}')) as t;

  return v_id;
end;
$$;


-- ---------------------------------------------------------------------
-- What the website shows. Only published reviews count, and the
-- voter_hash is never part of any view.
-- ---------------------------------------------------------------------

-- Per course: the money-grab meter, the AI slop meter and the rest.
create or replace view public.course_review_summary
with (security_invoker = true) as
select
  course_id,
  count(*)                                             as reviews,
  count(*) filter (where verdict = 'worth_it')         as worth_it,
  count(*) filter (where verdict = 'money_grab')       as money_grab,
  round(100.0 * count(*) filter (where verdict = 'worth_it') / count(*)) as worth_it_pct,
  round(avg(ai_slop), 1)                               as avg_ai_slop,
  count(ai_slop)                                       as ai_slop_ratings,
  round(avg(learned), 1)                               as avg_learned,
  round(avg(difficulty), 1)                            as avg_difficulty,
  count(*) filter (where took_course = 'dropped')      as dropped,
  count(comment)                                       as comments,
  max(updated_at)                                      as last_review_at
from public.course_reviews
where status = 'published'
group by course_id;

-- The same per platform (Udemy, Coursera, ...).
create or replace view public.platform_review_summary
with (security_invoker = true) as
select
  platform,
  count(*)                                             as reviews,
  count(*) filter (where verdict = 'worth_it')         as worth_it,
  count(*) filter (where verdict = 'money_grab')       as money_grab,
  round(100.0 * count(*) filter (where verdict = 'worth_it') / count(*)) as worth_it_pct,
  round(avg(ai_slop), 1)                               as avg_ai_slop,
  round(avg(learned), 1)                               as avg_learned,
  count(*) filter (where took_course = 'dropped')      as dropped
from public.course_reviews
where status = 'published'
group by platform;

-- How often each tag was picked for each course ("Top tags").
create or replace view public.course_tag_counts
with (security_invoker = true) as
select r.course_id, t.code as tag, t.label, t.kind, count(*) as uses
from public.course_review_tags rt
join public.course_reviews r on r.id = rt.review_id and r.status = 'published'
join public.review_tags t on t.code = rt.tag
group by r.course_id, t.code, t.label, t.kind;

-- The reviews themselves, with helpful counts and tags.
create or replace view public.course_review_feed
with (security_invoker = true) as
select
  r.id, r.course_id, r.platform, r.took_course, r.verdict,
  r.ai_slop, r.learned, r.difficulty, r.paid, r.comment,
  r.created_at, r.updated_at,
  h.helpful, h.not_helpful,
  coalesce(tg.tags, '{}') as tags
from public.course_reviews r
left join lateral (
  select count(*) filter (where v.helpful)     as helpful,
         count(*) filter (where not v.helpful) as not_helpful
  from public.review_helpful_votes v
  where v.review_id = r.id
) h on true
left join lateral (
  select array_agg(t.tag order by t.tag) as tags
  from public.course_review_tags t
  where t.review_id = r.id
) tg on true
where r.status = 'published';


-- ---------------------------------------------------------------------
-- Lock it down. The public key can't read or write anything here; only
-- the website's server, using the project's secret key, can. Newer
-- Supabase projects no longer give new tables API access by default,
-- so the secret key (service_role) gets exactly what it needs.
-- ---------------------------------------------------------------------
alter table public.course_reviews       enable row level security;
alter table public.review_tags          enable row level security;
alter table public.course_review_tags   enable row level security;
alter table public.review_helpful_votes enable row level security;
alter table public.review_reports       enable row level security;

revoke all on
  public.course_reviews, public.review_tags, public.course_review_tags,
  public.review_helpful_votes, public.review_reports,
  public.course_review_summary, public.platform_review_summary,
  public.course_tag_counts, public.course_review_feed
from anon, authenticated;

revoke all on function public.hide_reported_review() from public, anon, authenticated;
revoke all on function public.submit_review(
  bigint, text, text, text, text, integer, integer, integer, text, text, text[]
) from public, anon, authenticated;

grant select, insert, update, delete on public.course_reviews       to service_role;
grant select                         on public.review_tags          to service_role;
grant select, insert, delete         on public.course_review_tags   to service_role;
grant select, insert, update, delete on public.review_helpful_votes to service_role;
grant select, insert                 on public.review_reports       to service_role;
grant select on
  public.course_review_summary, public.platform_review_summary,
  public.course_tag_counts, public.course_review_feed
to service_role;
grant execute on function public.submit_review(
  bigint, text, text, text, text, integer, integer, integer, text, text, text[]
) to service_role;

-- Tell the API to pick up the changes right away.
notify pgrst, 'reload schema';
