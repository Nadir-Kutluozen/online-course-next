-- =====================================================================
-- OnlineCourseCompare: database setup for "Worth it or money grab?" votes
--
-- Run this once in a new Supabase project:
--   Supabase dashboard -> your project -> SQL Editor -> New query
--   -> paste this whole file -> Run
--
-- Safe to run again: it only creates what is missing and changes nothing
-- else. It creates the structure only. Votes people have already cast are
-- data; back those up separately (see the setup guide PDF).
--
-- The course list itself is NOT in the database. It lives in the website
-- (src/data/courses.json), so the site keeps working even if this
-- database is paused or gone. Only voting depends on it.
-- =====================================================================


-- One row per visitor per course. Nobody signs in. voter_hash is a one-way
-- hash the website's server makes from the visitor's connection, so a
-- visitor can change their vote but can't vote twice, and no IP address
-- is ever stored.
create table if not exists public.course_votes (
  id          bigint generated by default as identity primary key,
  course_id   bigint      not null,   -- "id" from src/data/courses.json
  platform    text        not null,   -- 'Udemy', 'Coursera', ...
  verdict     text        not null check (verdict in ('worth_it', 'money_grab')),
  voter_hash  text        not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint course_votes_one_per_voter unique (course_id, voter_hash)
);

create index if not exists course_votes_platform_idx
  on public.course_votes (platform);


-- Totals the website shows: per course, and per platform.
create or replace view public.course_vote_totals
with (security_invoker = true) as
select
  course_id,
  count(*) filter (where verdict = 'worth_it')   as worth_it,
  count(*) filter (where verdict = 'money_grab') as money_grab,
  count(*)                                       as total
from public.course_votes
group by course_id;

create or replace view public.platform_vote_totals
with (security_invoker = true) as
select
  platform,
  count(*) filter (where verdict = 'worth_it')   as worth_it,
  count(*) filter (where verdict = 'money_grab') as money_grab,
  count(*)                                       as total
from public.course_votes
group by platform;


-- Lock it down. The public key can't read or write votes; only the
-- website's server, using the project's secret key, can.
alter table public.course_votes enable row level security;

revoke all on public.course_votes         from anon, authenticated;
revoke all on public.course_vote_totals   from anon, authenticated;
revoke all on public.platform_vote_totals from anon, authenticated;

-- Newer Supabase projects no longer give new tables API access by
-- default, so give the secret key (service_role) exactly what it needs.
grant select, insert, update on public.course_votes      to service_role;
grant select on public.course_vote_totals, public.platform_vote_totals
  to service_role;

-- Tell the API to pick up the changes right away.
notify pgrst, 'reload schema';
